func (h *Handler) authorizeRoute(w http.ResponseWriter, r *http.Request, a *model.Account) bool {
	if a.Role == "admin" {
		return true
	}
	_, pattern := h.protected.Handler(r)
	policy := routeAuthorization[pattern][r.Method]
	if actions, ok := dynamicRouteAuthorization[pattern]; ok {
		action := r.URL.Path[strings.LastIndex(r.URL.Path, "/")+1:]
		if r.Method != "POST" || !actions[action] {
			h.failure(w, r, model.ErrForbidden)
			return false
		}
		policy = "editor"
	}

	switch policy {
	case "self", "read", "personal":
		return true
	case "editor":
		allowed, e := h.svc.HasEditingLibrary(r.Context())
		if e != nil {
			h.failure(w, r, e)
			return false
		}
		if allowed {
			return true
		}
	}
	h.failure(w, r, model.ErrForbidden)
	return false
}

